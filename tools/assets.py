#!/usr/bin/env python3
"""Import art + sound for a game from the Media Helper's drop and write <game>/assets/manifest.js.

  .venv/bin/python tools/assets.py import <game> [--from <drop>/deliveries/pocket-prototypes]
  .venv/bin/python tools/assets.py manifest [<game> ...]      # rebuild manifest(s) from what is in <game>/assets/

Images (img/*.png|jpg|webp) -> img/<name>.webp: a plain backdrop is keyed out to transparency (flood fill from the
edges; not for bg-*), the subject is trimmed and re-centred on a square, then resized (hero-* 256 px, bg-* 780 px wide,
everything else 384 px). Sounds (sfx/*.mp3|wav|ogg) -> sfx/<name>.mp3, mono 44.1 kHz, leading silence trimmed.
manifest.js sets window.PP_ASSETS = {img: {name: url?h=hash}, sfx: {...}}; the hash busts caches when a file changes,
and as a script it is hashed by the kit's new-version check, so phones reload when art lands.
"""
import hashlib, json, os, subprocess, sys
from collections import deque
from PIL import Image

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
GAMES = ['ore-sweeper', 'hoard', 'starfall', 'bonk-knight', 'void-drifter', 'delve-deck']
DROP = '/private/tmp/claude-501/-Users-matthewshort-claude-random-requests/9bc3d657-5733-4365-80e8-54214d2cba14/scratchpad/cpf-assets/deliveries/pocket-prototypes'

def key_out(im, tol=38):
    """Flood-fill the backdrop from every edge pixel whose colour is close to the corner colour; those pixels go clear."""
    im = im.convert('RGBA'); w, h = im.size; px = im.load()
    if sum(px[x, y][3] < 16 for x, y in ((0, 0), (w - 1, 0), (0, h - 1), (w - 1, h - 1))) >= 3: return im  # already transparent
    ref = px[0, 0][:3]
    near = lambda c: sum(abs(a - b) for a, b in zip(c[:3], ref)) <= tol
    seen = bytearray(w * h); q = deque()
    for x in range(w):
        for y in (0, h - 1): q.append((x, y))
    for y in range(h):
        for x in (0, w - 1): q.append((x, y))
    while q:
        x, y = q.popleft(); i = y * w + x
        if seen[i]: continue
        seen[i] = 1
        if not near(px[x, y]): continue
        px[x, y] = (0, 0, 0, 0)
        if x > 0: q.append((x - 1, y))
        if x < w - 1: q.append((x + 1, y))
        if y > 0: q.append((x, y - 1))
        if y < h - 1: q.append((x, y + 1))
    return im

def square(im, pad=0.04):
    bb = im.getbbox()
    if bb: im = im.crop(bb)
    s = int(max(im.size) * (1 + pad * 2)); out = Image.new('RGBA', (s, s), (0, 0, 0, 0))
    out.paste(im, ((s - im.width) // 2, (s - im.height) // 2)); return out

def do_image(src, dst_dir, name):
    im = Image.open(src)
    if name.startswith('bg-'):
        im = im.convert('RGB'); w = 780; im = im.resize((w, round(im.height * w / im.width)), Image.LANCZOS)
    else:
        im = square(key_out(im)); side = 256 if name.startswith('hero-') else 384
        im = im.resize((side, side), Image.LANCZOS)
    out = os.path.join(dst_dir, name + '.webp'); im.save(out, 'WEBP', quality=86, method=6); return out

def do_sound(src, dst_dir, name):
    out = os.path.join(dst_dir, name + '.mp3')
    subprocess.run(['ffmpeg', '-v', 'error', '-y', '-i', src, '-ac', '1', '-ar', '44100', '-af', 'silenceremove=start_periods=1:start_threshold=-50dB', '-b:a', '96k', out], check=True)
    return out

def manifest(game):
    base = os.path.join(ROOT, game, 'assets'); m = {'img': {}, 'sfx': {}}
    for kind in m:
        d = os.path.join(base, kind)
        for f in sorted(os.listdir(d)) if os.path.isdir(d) else []:
            if f.startswith('.'): continue
            h = hashlib.sha1(open(os.path.join(d, f), 'rb').read()).hexdigest()[:8]
            m[kind][os.path.splitext(f)[0]] = 'assets/%s/%s?h=%s' % (kind, f, h)
    os.makedirs(base, exist_ok=True)
    with open(os.path.join(base, 'manifest.js'), 'w') as f:
        f.write('// generated by tools/assets.py: do not edit\nwindow.PP_ASSETS = %s;\n' % json.dumps(m, indent=1, sort_keys=True))
    return m

def do_import(game, drop):
    src = os.path.join(drop, game, 'assets'); n = 0
    for kind, fn, exts in (('img', do_image, ('.png', '.jpg', '.jpeg', '.webp')), ('sfx', do_sound, ('.mp3', '.wav', '.ogg', '.flac'))):
        d = os.path.join(src, kind)
        if not os.path.isdir(d): continue
        dst = os.path.join(ROOT, game, 'assets', kind); os.makedirs(dst, exist_ok=True)
        for f in sorted(os.listdir(d)):
            name, ext = os.path.splitext(f)
            if ext.lower() not in exts: continue
            out = fn(os.path.join(d, f), dst, name.lower()); n += 1
            print('  %-28s -> %s (%d KB)' % (f, os.path.relpath(out, ROOT), os.path.getsize(out) // 1024))
    m = manifest(game); print('%s: %d imported; manifest has %d images, %d sounds' % (game, n, len(m['img']), len(m['sfx'])))

if __name__ == '__main__':
    a = sys.argv[1:]
    if a[:1] == ['import'] and len(a) >= 2:
        drop = a[a.index('--from') + 1] if '--from' in a else DROP
        do_import(a[1], drop)
    elif a[:1] == ['manifest']:
        for g in a[1:] or GAMES: m = manifest(g); print(g, len(m['img']), 'images', len(m['sfx']), 'sounds')
    else: print(__doc__); sys.exit(2)
